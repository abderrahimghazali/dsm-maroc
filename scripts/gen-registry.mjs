// Generates src/content/registry.generated.tsx from src/content/examples/<slug>/{meta.ts,*.tsx}
import { readdirSync, readFileSync, writeFileSync, existsSync, statSync } from "node:fs";
import { join } from "node:path";

const root = new URL("../src/content/examples/", import.meta.url).pathname;
const out = new URL("../src/content/registry.generated.tsx", import.meta.url).pathname;

const dirs = existsSync(root)
  ? readdirSync(root).filter((d) => statSync(join(root, d)).isDirectory() && existsSync(join(root, d, "meta.ts")))
  : [];

const ident = (s) => s.replace(/[^a-zA-Z0-9]/g, "_");
let imports = [];
let entries = [];

for (const slug of dirs.sort()) {
  const dir = join(root, slug);
  const files = readdirSync(dir).filter((f) => f.endsWith(".tsx") && f !== "meta.ts");
  imports.push(`import meta_${ident(slug)} from "./examples/${slug}/meta";`);
  const examples = [];
  for (const f of files.sort()) {
    const ex = f.replace(/\.tsx$/, "");
    const id = `ex_${ident(slug)}_${ident(ex)}`;
    imports.push(`import ${id} from "./examples/${slug}/${ex}";`);
    const source = readFileSync(join(dir, f), "utf8").replace(/^"use client";\s*\n/, "");
    examples.push(`    ${JSON.stringify(ex)}: { Component: ${id}, source: ${JSON.stringify(source)} },`);
  }
  entries.push(`  {\n    meta: meta_${ident(slug)},\n    examples: {\n${examples.join("\n")}\n    },\n  },`);
}

const code = `// AUTO-GENERATED by scripts/gen-registry.mjs — do not edit.
import type { ComponentType } from "react";
import type { ComponentMeta } from "./types";
${imports.join("\n")}

export type RegistryEntry = {
  meta: ComponentMeta;
  examples: Record<string, { Component: ComponentType; source: string }>;
};

export const registry: RegistryEntry[] = [
${entries.join("\n")}
];
`;
writeFileSync(out, code);
console.log(`registry: ${dirs.length} components, written to src/content/registry.generated.tsx`);
