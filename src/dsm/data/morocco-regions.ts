// Same equirectangular projection the paths were generated with (x scaled by cos of the mid-latitude).
const LON0 = -17.2;
const LON1 = -0.9;
const LAT0 = 20.7;
const LAT1 = 36.0;
const PAD = 8;
const K = Math.cos((((LAT0 + LAT1) / 2) * Math.PI) / 180);
const SX = (560 - 2 * PAD) / ((LON1 - LON0) * K);

/** Project a geographic position onto the map's viewBox: [x, y] in the 560 × 596 space. */
export function projectMoroccoPoint(lon: number, lat: number): [number, number] {
  return [(lon - LON0) * K * SX + PAD, (LAT1 - lat) * SX + PAD];
}
